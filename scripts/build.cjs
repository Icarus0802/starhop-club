'use strict';
const fs=require('node:fs'),path=require('node:path');
const root=path.resolve(__dirname,'..');
const read=file=>fs.readFileSync(path.join(root,'js',file),'utf8').replace(/\r\n/g,'\n');
const source=['engine.js','ai.js','fast-search.js','team-planner.js','race-finish.js','friendly-finish.js','finish-policy.js','repetition-rule.js'].map(read).join('\n')+'\n'+read('worker.js').replace(/^importScripts[^\n]*\n/,'');
fs.writeFileSync(path.join(root,'js','worker-bundle.js'),'// Generated by node scripts/build.cjs; supports offline file:// Web Workers.\nwindow.STARHOP_WORKER_SOURCE = '+JSON.stringify(source)+';\n');
console.log('Offline AI worker bundle ready.');
